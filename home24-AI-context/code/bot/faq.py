# «Уважаемый менеджер, ответьте мне» — просьба ответить, а не передача (промпт, аудит S1/S10)
_POLITE_ANSWER_RE = re.compile(r"(?i)менеджер\W.*\bответ(ь|ьте)|ответ(ь|ьте)\W.*менеджер")
_REAL_HANDOFF_RE = re.compile(
    r"(?i)позов|позва|свяж|подключ|соедин|живо(й|го)\s+человек|передай|переключ|оператор"
)
# «на 3 человека», «двое человек» — это гости, не просьба позвать человека
_HEADCOUNT_RE = re.compile(
    r"(?i)(\d+|дв|тр|четыр|пят|шест|сем|вос|нескольк|скольк)\w*\s*(-?х)?\s*человек"
)
_COMPLAINT_KEYS = (
    "жалоб",
    "плохо было",
    "ужас",
    "кошмар",
    "возмущ",
    "недоволен",
    "недовольна",
    "сломал",
    "сломан",
    "грязн",
)


def match_faq(text: str) -> tuple[list[str], str | None] | None:
    """Вернёт (messages, special_code) или None. special: escalate | bonus | hello | thanks."""
    t = (text or "").lower().strip()
    if not t:
        return None
    from bot.tone import classify

    tone = classify(text or "")
    if tone:
        kind, line = tone
        return [line], kind
    # «Уважаемый менеджер, ответьте мне» без «позовите / свяжите» — я тут, не передача
    if _POLITE_ANSWER_RE.search(t) and not _REAL_HANDOFF_RE.search(t):
        return ["Да, я тут, слушаю вас."], None
    # ранний заезд + поздний выезд в одном вопросе
    if re.search(r"(?i)ранн\w*\s*заезд|заехать\s*(по)?раньше|пораньше\s*заех", t) and re.search(
        r"(?i)поздн\w*\s*выезд|(выехать|уехать)\s*(по)?позже|(по)?позже\s*(выех|уех)", t
    ):
        return [
            "Ранний заезд и поздний выезд иногда можно, если квартира свободна. "
            "Напишите желаемое время — уточню по выбранной квартире."
        ], None
    headcount = bool(_HEADCOUNT_RE.search(t))
    tp = t + " "  # ключи вида «ау », «хай », «тв » срабатывают и в конце фразы
    for keys, msgs in FAQ_RULES:
        for k in keys:
            if k not in tp:
                continue
            if k == "человека" and headcount:
                continue
            special = None
            # привет / спасибо — вариативные реплики в engine
            if any(x in keys for x in ("привет", "здравствуй", "здрасьте")):
                return [], "hello"
            if any(x in keys for x in ("спасибо", "благодар", "спс", "пасиб")):
                return [], "thanks"
            wants_human = any(
                x in t for x in ("позовите", "живого", "живой человек", "менеджер", "оператор")
            ) or ("человек" in t and not headcount)
            if wants_human:
                special = "escalate"
            if any(x in t for x in ("бонус", "баллы", "лояльност")) and "скидк" not in t:
                special = special or "bonus_hint"
            if any(x in t for x in _COMPLAINT_KEYS):
                special = "escalate"
            # цена / наличие — только менеджер, без выдуманных фактов
            if any(
                x in keys
                for x in ("цена", "сколько стоит", "стоимость", "свободн", "наличие")
            ):
                special = "escalate"
            return [m for m in msgs], special
    return None


def faq_then_resume(
    faq_msgs: list[str],
    step: str,
    buttons_map: dict[str, Any],
) -> tuple[list[str], list[tuple[str, str]] | None]:
    """Ответить на FAQ и мягко вернуть к текущему шагу воронки."""
    msgs = list(faq_msgs)
    if not msgs:
        return msgs, None
    from bot.phrases import district_choice_message

    ask_district = district_choice_message()
    resume = {
        "await_district": (ask_district, "district"),
        "await_dates": ("На какие даты смотрите?", "dates"),
        "await_guests": ("Сколько вас будет?", "guests"),
        "await_returning": ("Вы у нас уже были или впервые?", "returning"),
        "await_favorite": ("Напишите название или адрес квартиры, которая понравилась)", None),
        "browsing": ("Скинуть пару вариантов на потом?", "browsing"),
        "await_intent": (ask_district, "greeting"),
        "greeting": (ask_district, "greeting"),
    }
    if step in resume:
        q, bkey = resume[step]
        blob = " ".join(msgs).lower()
        # не клеить тот же вопрос поверх FAQ
        skip = False
        if step == "await_dates" and "дат" in blob:
            skip = True
        elif step == "await_guests" and re.search(r"человек|гост", blob):
            skip = True
        elif step == "await_district" and re.search(r"район|центр", blob):
            skip = True
        elif step == "await_returning" and re.search(r"впервые|были", blob):
            skip = True
        elif "?" in blob:  # в ответе уже есть свой вопрос — второй не клеим
            skip = True
        if not skip:
            msgs.append(q)
        buttons = buttons_map.get(bkey) if bkey else None
        return msgs, buttons
    return msgs, None
