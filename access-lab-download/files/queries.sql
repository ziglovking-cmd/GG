-- 4.1 Запрос на выборку «Список студентов»
SELECT Группы.Группа, Студенты.[№Зачетки], Студенты.Фамилия, Студенты.Имя
FROM Группы
INNER JOIN Студенты ON Группы.Группа = Студенты.Группа
ORDER BY Студенты.Фамилия, Студенты.Имя;

-- 4.2 Запрос с параметром (в Access: Список Студентов1)
SELECT Группы.Группа, Студенты.[№Зачетки], Студенты.Фамилия, Студенты.Имя
FROM Группы
INNER JOIN Студенты ON Группы.Группа = Студенты.Группа
WHERE Группы.Группа = [Введите группу];

-- 4.3 Запрос без подчиненных — группы без студентов
SELECT Группы.*
FROM Группы
LEFT JOIN Студенты ON Группы.Группа = Студенты.Группа
WHERE Студенты.Группа Is Null;

-- 4.4 Повторяющиеся записи в «Успеваемость»
-- (в Access удобнее Мастер «Повторяющиеся записи»; идея запроса:)
SELECT Успеваемость.[№Зачетки], Успеваемость.Семестр, Успеваемость.Дисциплины,
       Успеваемость.ФормаКонтроля, Успеваемость.Оценка, Успеваемость.Преподаватель,
       Count(*) AS Количество
FROM Успеваемость
GROUP BY Успеваемость.[№Зачетки], Успеваемость.Семестр, Успеваемость.Дисциплины,
         Успеваемость.ФормаКонтроля, Успеваемость.Оценка, Успеваемость.Преподаватель
HAVING Count(*) > 1;

-- 4.5 Многотабличный запрос «Успеваемость студентов»
SELECT Группы.Группа, Успеваемость.[№Зачетки], Студенты.Фамилия, Студенты.Имя,
       Успеваемость.Семестр, Успеваемость.Дисциплины, Успеваемость.ФормаКонтроля,
       Успеваемость.Оценка, Успеваемость.Дата, Успеваемость.Преподаватель
FROM (Группы
INNER JOIN Студенты ON Группы.Группа = Студенты.Группа)
INNER JOIN Успеваемость ON Студенты.[№Зачетки] = Успеваемость.[№Зачетки];

-- 4.6 Перекрестный запрос (на основе предыдущего)
TRANSFORM First([Успеваемость студентов].Оценка) AS Оценка
SELECT [Успеваемость студентов].Дисциплины
FROM [Успеваемость студентов]
GROUP BY [Успеваемость студентов].Дисциплины
PIVOT [Успеваемость студентов].Фамилия;

-- 5.1 Количество студентов в группах
SELECT Группы.Группа, Count(Студенты.[№Зачетки]) AS [Count-№Зачетки]
FROM Группы
LEFT JOIN Студенты ON Группы.Группа = Студенты.Группа
GROUP BY Группы.Группа;

-- 5.2 Отбор по дате рождения
SELECT Студенты.[№Зачетки], Студенты.Фамилия, Студенты.Имя, Студенты.Рожден, Студенты.Группа
FROM Студенты
WHERE Студенты.Рожден >= #1/1/1995# And Студенты.Рожден <= #1/1/2006#;

-- 5.3 Вычисляемое поле ФИО
SELECT [Фамилия] & " " & Left([Имя],1) & "." & Left([Отчество],1) & "." AS ФИО,
       Студенты.Группа
FROM Студенты
ORDER BY Студенты.Фамилия;

