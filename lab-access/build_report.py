def set_run_font(run, size=12, bold=False, name="Times New Roman"):
    run.font.name = name
    run._element.rPr.rFonts.set(qn("w:eastAsia"), name)
    run.font.size = Pt(size)
    run.bold = bold


def add_p(text="", *, size=12, bold=False, align="left", space_after=6, space_before=0):
    p = doc.add_paragraph()
    if align == "center":
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    elif align == "right":
        p.alignment = WD_ALIGN_PARAGRAPH.RIGHT
    elif align == "justify":
        p.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    p.paragraph_format.space_after = Pt(space_after)
    p.paragraph_format.space_before = Pt(space_before)
    p.paragraph_format.line_spacing = 1.15
    if text:
        run = p.add_run(text)
        set_run_font(run, size=size, bold=bold)
    return p


def add_heading_custom(text, level=1):
    sizes = {1: 16, 2: 14, 3: 13}
    add_p(text, size=sizes.get(level, 12), bold=True, align="left", space_before=12, space_after=8)


def add_img(path, width=15.5):
    path = Path(path)
    if not path.exists():
        add_p(f"[нет скрина: {path.name}]", size=10)
        return
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    run = p.add_run()
    run.add_picture(str(path), width=Cm(width))
    p.paragraph_format.space_after = Pt(4)


def add_caption(text):
    add_p(text, size=11, align="center", space_after=10)


def qa(q, a):
    add_p(q, size=12, bold=True, space_before=6, space_after=2)
    add_p(a, size=12, align="justify", space_after=6)


