"""Contracts used by invitation use cases; implemented at the outer boundary."""
from __future__ import annotations

from typing import Any, Awaitable, Callable, Dict, List, Mapping, Optional, Protocol

from app.domain.invitations import TargetSelection


class InvitationRepository(Protocol):
    def campaign_stats(self, campaign_id: int) -> Dict[str, int]: ...
    def has_unresolved_targets(self, campaign_id: int) -> bool: ...
    def populate_targets(
        self,
        campaign_id: int,
        source_chat_ids: List[int],
        selection: TargetSelection,
    ) -> int: ...
    def mark(
        self,
        target_id: int,
        status: str,
        account_id: Optional[int],
        error: str = '',
    ) -> None: ...
    def requeue_after_technical_failure(self, target_id: int) -> None: ...
    def requeue_safe_pre_rpc_claims(self, campaign_id: int) -> None: ...
    def claim_target(self, campaign_id: int, account_id: int) -> Optional[Dict[str, Any]]: ...
    def mark_unreachable(self, campaign_id: int, account_ids: List[int]) -> int: ...
    def get_campaign(self, campaign_id: int) -> Optional[Dict[str, Any]]: ...
    def get_account(self, account_id: int) -> Optional[Dict[str, Any]]: ...
    def get_chat(self, chat_id: int) -> Optional[Dict[str, Any]]: ...
    def get_hash(self, account_id: int, user_id: int) -> Optional[Dict[str, Any]]: ...
    def save_hash(
        self,
        account_id: int,
        user_id: int,
        access_hash: int,
        updated_at: int,
    ) -> int: ...
    def running_for_chat(self, chat_id: int) -> List[Mapping[str, Any]]: ...
    def save_resolved_id(self, user_id: int, target_id: int) -> int: ...
    def save_verification_error(self, error: str, target_id: int) -> int: ...
    def campaign_next_invite(self, campaign_id: int) -> Optional[Dict[str, Any]]: ...
    def reserve_campaign(self, next_at: int, campaign_id: int) -> int: ...
    def release_campaign(self, campaign_id: int, reserved_at: int) -> int: ...
    def restore_technical_account(self, account_id: int) -> int: ...
    def restore_account(self, account_id: int) -> int: ...
    def set_campaign_status(self, status: str, campaign_id: int) -> int: ...
    def pending_verification(
        self,
        campaign_id: int,
        account_id: int,
        marker: str,
    ) -> Optional[Dict[str, Any]]: ...
    def log(self, message: str, **context: Any) -> None: ...
    def mark_invite_rpc_started(self, target_id: int, account_id: int, note: str) -> bool: ...
    def finalize_invite_confirmation(self, target_id: int, present: bool, **kwargs: Any) -> str: ...


class AccountPort(Protocol):
    async def get_client(self, account_id: int) -> Any: ...
    async def drop_client(self, account_id: int) -> None: ...
    async def test_proxy(self, account_id: int) -> dict[str, Any]: ...
    def invite_eligibility(
        self,
        account: Optional[Dict[str, Any]],
        *,
        check_cooldown: bool = True,
        check_quota: bool = True,
    ) -> tuple[bool, str, str]: ...
    def quota_left(self, account: dict[str, Any]) -> int: ...
    def schedule_next_attempt(
        self,
        account_id: int,
        delay: int,
        now: Optional[int] = None,
    ) -> int: ...
    def defer_next_attempt(
        self,
        account_id: int,
        seconds: int,
        now: Optional[int] = None,
    ) -> int: ...
    def release_next_attempt(self, account_id: int, reserved_at: int) -> int: ...
    def set_cooldown(self, account_id: int, seconds: int, reason: str) -> None: ...
    def restrict_invites(self, account_id: int, reason: str) -> None: ...
    def register_delivery_outcome(
        self, account_id: int, outcome: str
    ) -> Optional[str]: ...
    def set_status(self, account_id: int, status: str, error: str = '') -> None: ...


class TelegramGateway(Protocol):
    async def is_authorized(self, client: Any) -> bool: ...
    async def resolve_target_chat(self, client: Any, target_chat_id: int) -> Any: ...
    async def resolve_peer(
        self,
        client: Any,
        account_id: int,
        user_id: int,
        username: Optional[str],
    ) -> Any: ...
    async def invite_one(self, client: Any, target_entity: Any, peer: Any) -> None: ...
    async def membership_state_once(
        self,
        client: Any,
        target_entity: Any,
        peer: Any,
    ) -> tuple[str, str]: ...
    def user_id(self, peer: Any) -> Optional[int]: ...
    def can_invite(self, entity: Any) -> bool: ...
    def is_rpc_error(self, error: BaseException) -> bool: ...
    def is_transient_connection_error(self, error: BaseException) -> bool: ...


class AttemptNotifier(Protocol):
    def set(self, notifier: Optional[Callable[[Dict[str, Any]], Awaitable[None]]]) -> None: ...
    def queue(
        self,
        campaign_id: int,
        account_id: int,
        target: Optional[dict[str, Any]],
        outcome: str,
        next_attempt_at: int,
        error: str = '',
    ) -> Optional[Awaitable[None]]: ...
