def write_md(path):
    parts = ["# Ответы на вопросы к зачёту по патологической физиологии\n",
             "> Ответы составлены **строго по тексту** файла «патфиз экз». Если пункт есть в формулировке вопроса, но не раскрыт в файле, это отмечено примечанием.\n"]
    for num, title, body in ANSWERS:
        parts.append(f"\n## {num}. {title}\n\n{body}\n")
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(parts))


def write_docx(path):
    doc = Document()
    section = doc.sections[0]
    section.top_margin = Cm(2)
    section.bottom_margin = Cm(2)
    section.left_margin = Cm(2.5)
    section.right_margin = Cm(2)

    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    h = doc.add_heading("Ответы на вопросы к зачёту по патологической физиологии", 0)
    h.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = doc.add_paragraph(
        "Ответы составлены строго по тексту файла «патфиз экз». "
        "Если пункт есть в формулировке вопроса, но не раскрыт в файле, это отмечено примечанием."
    )
    p.runs[0].italic = True

    for num, title, body in ANSWERS:
        doc.add_heading(f"{num}. {title}", level=1)
        for para in body.split("\n"):
            para = para.strip()
            if not para:
                continue
            doc.add_paragraph(para)

    doc.save(path)


